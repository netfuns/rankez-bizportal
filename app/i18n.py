def normalize_locale(raw: str | None) -> str:
    value = (raw or "").strip()
    if value in LOCALES:
        return value
    if value.lower().startswith("zh-tw") or value.lower().startswith("zh-hant"):
        return "zh-TW"
    if value.lower().startswith("zh"):
        return "zh-CN"
    return DEFAULT_LOCALE


def translate(locale: str, key: str, **fmt) -> str:
    if locale == "zh-CN":
        text = ZH_CN.get(key, key)
    elif locale == "zh-TW":
        text = ZH_TW.get(key) or ZH_CN.get(key, key)
    else:
        text = key
    if fmt:
        try:
            return text % fmt if fmt else text
        except (TypeError, ValueError):
            return text
    return text
